#!/bin/sh
set -eu

cd "$(dirname "$0")/.."
version=$(cat internal/checker/patches/go-version)
goroot=$(GOTOOLCHAIN="$version" go env GOROOT)
stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT HUP INT TERM

mkdir -p "$stage/ast"
for source in "$goroot/src/go/ast/"*.go; do
	case "$source" in
		*_test.go) continue ;;
	esac
	cp "$source" "$stage/ast/"
done

if ! patch -t -F 0 -p 1 -d "$stage" < internal/ast/patches/source.patch > "$stage/patch.log"; then
	cat "$stage/patch.log" >&2
	exit 1
fi
if grep -E 'offset|fuzz' "$stage/patch.log"; then
	echo 'Update the AST patch for the pinned Go source; shifted matches are not accepted.' >&2
	exit 1
fi

for source in "$stage/ast/"*.go; do
	{
		printf '// Code generated by scripts/prepare-ast.sh; DO NOT EDIT.\n\n'
		cat "$source"
	} > "internal/ast/$(basename "$source")"
done
