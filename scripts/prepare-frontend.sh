#!/bin/sh
set -eu

cd "$(dirname "$0")/.."
version=$(cat internal/checker/patches/go-version)
goroot=$(GOTOOLCHAIN="$version" go env GOROOT)
stage=$(mktemp -d)
trap 'rm -rf "$stage"' EXIT HUP INT TERM

for package in parser scanner; do
	mkdir -p "$stage/$package"
	for source in "$goroot/src/go/$package/"*.go; do
		case "$source" in
			*_test.go|*/errors.go) continue ;;
		esac
		cp "$source" "$stage/$package/"
	done
done

if ! patch -t -F 0 -p 1 -d "$stage" < internal/frontend/patches/source.patch > "$stage/patch.log"; then
	cat "$stage/patch.log" >&2
	exit 1
fi
if grep -E 'offset|fuzz' "$stage/patch.log"; then
	echo 'Update the frontend patch for the pinned Go source; shifted matches are not accepted.' >&2
	exit 1
fi

for package in parser scanner; do
	for source in "$stage/$package/"*.go; do
		{
			printf '// Code generated by scripts/prepare-frontend.sh; DO NOT EDIT.\n\n'
			cat "$source"
		} > "internal/frontend/$package/$(basename "$source")"
	done
done
