package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestFunctionComments checks named functions, methods, tests, and attached comment text.
func TestFunctionComments(t *testing.T) {
	for _, test := range []struct {
		name   string
		source string
		want   string
	}{
		{"private", "func helper() {}", "function helper needs a comment"},
		{"exported", "func Public() {}", "function Public needs a comment"},
		{"method", "type private struct{}\nfunc (private) Work() {}", "function Work needs a comment"},
		{"private_method", "type private struct{}\nfunc (private) work() {}", "function work needs a comment"},
		{"main", "func main() {}", "function main needs a comment"},
		{"init", "func init() {}", "function init needs a comment"},
		{"test", "func TestInput() {}", "function TestInput needs a comment"},
		{"benchmark", "func BenchmarkInput() {}", "function BenchmarkInput needs a comment"},
		{"blank", "//\nfunc helper() {}", "function helper needs a comment"},
		{"blank_block", "/* */\nfunc helper() {}", "function helper needs a comment"},
		{"go_directive", "//go:noinline\nfunc helper() {}", "function helper needs a comment"},
		{"line_directive", "//line virtual.go:10\nfunc helper() {}", "function helper needs a comment"},
		{"nolint", "//nolint:unused\nfunc helper() {}", "function helper needs a comment"},
		{"bare_nolint", "//nolint\nfunc helper() {}", "function helper needs a comment"},
		{"nolint_reason", "//nolint reason\nfunc helper() {}", "function helper needs a comment"},
		{"directive_name", "// nolintNames reports suppression names.\nfunc nolintNames() {}", ""},
		{"detached", "// helper reads input.\n\nfunc helper() {}", "function helper needs a comment"},
		{"attached", "// helper reads input.\nfunc helper() {}", ""},
		{"block", "/* helper reads input. */\nfunc helper() {}", ""},
		{"text_and_directive", "// helper reads input.\n//go:noinline\nfunc helper() {}", ""},
		{"literal", "var callback = func() {}", ""},
		{"generated", "// Code generated by test. DO NOT EDIT.\nfunc helper() {}", ""},
	} {
		t.Run(test.name, func(t *testing.T) {
			path := writeSource(t, test.name+".go", "package main\n"+test.source)
			err := checkFunctionFiles([]string{path})
			if test.want == "" {
				if err != nil {
					t.Fatal(err)
				}
				return
			}
			if err == nil || !strings.Contains(err.Error(), test.want) || !strings.Contains(err.Error(), path+":") {
				t.Fatalf("error = %v; want file position and %q", err, test.want)
			}
		})
	}
}

// TestFunctionFileExclusions checks fixture and generated-output paths before reading them.
func TestFunctionFileExclusions(t *testing.T) {
	if err := checkFunctionFiles([]string{
		"", "tests/testdata/input/main.go", "nested/tests/testdata/input/main.go",
		"missing_tgo.go", "missing_tgo_test.go",
	}); err != nil {
		t.Fatal(err)
	}
}

// TestFunctionFileErrors checks that syntax errors and missing files fail the lint command.
func TestFunctionFileErrors(t *testing.T) {
	invalid := writeSource(t, "invalid.go", "package main\nfunc broken(")
	for _, path := range []string{invalid, filepath.Join(t.TempDir(), "missing.go")} {
		if err := checkFunctionFiles([]string{path}); err == nil {
			t.Fatalf("accepted unreadable source %s", path)
		}
	}
}

// TestFunctionCommentsReportAll checks that the gate reports each undocumented function.
func TestFunctionCommentsReportAll(t *testing.T) {
	path := writeSource(t, "input.go", "package main\nfunc first() {}\nfunc second() {}")
	err := checkFunctionFiles([]string{path})
	if err == nil || !strings.Contains(err.Error(), path+":2:1: function first") ||
		!strings.Contains(err.Error(), path+":3:1: function second") {
		t.Fatalf("missing function positions: %v", err)
	}
}

// writeSource writes a Go input in a test directory and returns its path.
func writeSource(t *testing.T, name, source string) string {
	t.Helper()
	path := filepath.Join(t.TempDir(), name)
	if err := os.WriteFile(path, []byte(source), 0600); err != nil {
		t.Fatal(err)
	}
	return path
}
