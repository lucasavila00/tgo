def header(adaptation: Adaptation) -> str:
    """Return the required Go Authors header."""
    return (
        f"// Copyright {adaptation.year} The Go Authors. All rights reserved.\n"
        "// Use of this source code is governed by a BSD-style\n"
        f"// license that can be found in {adaptation.license_path}.\n"
    )


def is_generated_go(path: Path) -> bool:
    """Report whether a path is in the TGo output namespace."""
    if path.suffix != ".go":
        return False
    stem = path.stem
    if stem.endswith("_test"):
        stem = stem.removesuffix("_test")
    if stem.endswith("_tgo"):
        return True
    marker = stem.rfind("_tgo_")
    if marker < 0:
        return False
    target = stem[marker + len("_tgo_"):].split("_")
    if len(target) == 1:
        return target[0] in TARGET_OSES or target[0] in TARGET_ARCHITECTURES
    if len(target) == 2:
        return target[0] in TARGET_OSES and target[1] in TARGET_ARCHITECTURES
    return False


def handwritten_sources(repository: Path) -> list[Path]:
    """Return handwritten production Go and TGo source paths."""
    result: list[Path] = []
    for source_root in sorted(SOURCE_ROOTS):
        root = repository / source_root
        if not root.is_dir():
            continue
        for path in root.rglob("*"):
            if not path.is_file() or path.suffix not in {".go", ".tgo"}:
                continue
            relative = path.relative_to(repository)
            directories = relative.parts[:-1]
            if any(
                name.startswith((".", "_")) or name in SKIPPED_DIRECTORIES
                for name in directories
            ):
                continue
            if path.name.endswith(("_test.go", "_test.tgo")):
                continue
            if is_generated_go(path):
                continue
            if path.read_text(encoding="utf-8").startswith(GENERATED_NOTICE):
                continue
            result.append(relative)
    return sorted(result)


def failures(
    repository: Path = ROOT,
    adaptations: dict[str, Adaptation] = ADAPTATIONS,
) -> list[str]:
    """Return attribution and source-map failures."""
    result: list[str] = []
    documentation: dict[str, str] = {}
    for name, adaptation in adaptations.items():
        path = repository / name
        if not path.is_file():
            result.append(f"{name}: adapted source does not exist")
            continue
        if not path.read_text(encoding="utf-8").startswith(header(adaptation)):
            result.append(f"{name}: adapted source has no required header")

        document = repository / adaptation.documentation
        if not document.is_file():
            result.append(
                f"{name}: provenance document does not exist: "
                f"{adaptation.documentation}"
            )
            continue
        content = documentation.setdefault(
            adaptation.documentation,
            document.read_text(encoding="utf-8"),
        )
        sources = ", ".join(f"`{source}`" for source in adaptation.sources)
        row = f"| `{name}` | {sources} |"
        if row not in content:
            result.append(f"{name}: source map is absent from documentation")

    for path in handwritten_sources(repository):
        source = (repository / path).read_text(encoding="utf-8")
        if GO_COPYRIGHT.match(source) and path.as_posix() not in adaptations:
            result.append(f"{path}: Go Authors header has no provenance entry")
    return result


def main() -> int:
    """Report each incomplete upstream attribution."""
    result = failures()
    for failure in result:
        print(failure)
    return 1 if result else 0


if __name__ == "__main__":
    sys.exit(main())
