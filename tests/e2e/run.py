def check_output_safety(compiler, temporary):
    work = temporary / "output-safety"
    work.mkdir()
    (work / "go.mod").write_text("module output.test\n\ngo 1.27.0\n")
    model = work / "model"
    model.mkdir()
    source = model / "model.tgo"
    output = model / "model_tgo.go"
    source.write_text("package model\n\nfunc Value() int { return 1 }\n")

    outside = temporary / "outside.go"
    outside_data = b"// Code generated by tgo. DO NOT EDIT.\n\npackage model\n"
    outside.write_bytes(outside_data)
    try:
        output.symlink_to(outside)
    except OSError:
        pass
    else:
        result = run([str(compiler), "build", "./model"], work, success=False)
        assert "refusing non-regular output" in result, result
        assert output.is_symlink(), "compiler replaced an output symlink"
        assert outside.read_bytes() == outside_data
        output.unlink()

        orphan_link = work / "orphan-link"
        orphan_link.mkdir()
        stale_link = orphan_link / "stale_tgo.go"
        stale_link.symlink_to(outside)
        result = run(
            [str(compiler), "build", "./orphan-link"],
            work,
            success=False,
        )
        assert "refusing non-regular output" in result, result
        assert stale_link.is_symlink(), "compiler removed an orphan symlink"

    output.write_text("package model\n\nfunc UserFile() {}\n")
    run([str(compiler), "build", "./model"], work)
    assert output.read_bytes() == source.read_bytes(), "compiler kept a reserved collision"
    output.chmod(0o600)
    output_mode = stat.S_IMODE(output.stat().st_mode)
    run([str(compiler), "build", "./model"], work)
    assert stat.S_IMODE(output.stat().st_mode) == output_mode

    original = output.read_bytes()
    failure = work / "z_failure"
    failure.mkdir()
    (failure / "failure.tgo").write_text("package failure\n\ntype\n")
    source.write_text("package model\n\nfunc Value() int { return 2 }\n")
    run(
        [str(compiler), "build", "./model", "./z_failure"],
        work,
        success=False,
    )
    assert output.read_bytes() == original, "rollback changed output content"
    assert stat.S_IMODE(output.stat().st_mode) == output_mode
    assert not list(model.glob(".*.tmp-*")), "compiler left a temporary output"

    new_package = work / "new-package"
    new_package.mkdir()
    (new_package / "new.tgo").write_text(
        "package newpackage\n\nfunc Value() int { return 1 }\n"
    )
    run(
        [str(compiler), "build", "./new-package", "./z_failure"],
        work,
        success=False,
    )
    assert not (new_package / "new_tgo.go").exists()

    stale = work / "stale"
    stale.mkdir()
    stale_output = stale / "old_tgo.go"
    stale_data = b"// Code generated by tgo. DO NOT EDIT.\n\npackage stale\n"
    stale_output.write_bytes(stale_data)
    stale_output.chmod(0o640)
    stale_mode = stat.S_IMODE(stale_output.stat().st_mode)
    run(
        [str(compiler), "build", "./stale", "./z_failure"],
        work,
        success=False,
    )
    assert stale_output.read_bytes() == stale_data
    assert stat.S_IMODE(stale_output.stat().st_mode) == stale_mode

    lock_work = temporary / "lock-safety"
    lock_work.mkdir()
    (lock_work / "go.mod").write_text("module lock.test\n\ngo 1.27.0\n")
    (lock_work / "value.tgo").write_text(
        "package locktest\n\nfunc Value() int { return 1 }\n"
    )
    lock_path = lock_work / ".tgo.lock"
    lock_target = temporary / "lock-target"
    lock_target.write_text("unchanged")
    try:
        lock_path.symlink_to(lock_target)
    except OSError:
        pass
    else:
        result = run([str(compiler), "build"], lock_work, success=False)
        assert "refusing non-regular lock file" in result, result
        assert lock_target.read_text() == "unchanged"
        lock_path.unlink()
    run([str(compiler), "build"], lock_work)
    assert lock_path.is_file(), "compiler did not create its module lock"

    if os.name == "posix":
        with lock_path.open("rb") as held_lock:
            fcntl.flock(held_lock, fcntl.LOCK_EX)
            waiting = subprocess.Popen(
                [str(compiler), "build"],
                cwd=lock_work,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.PIPE,
            )
            time.sleep(0.2)
            assert waiting.poll() is None, "compiler did not wait for the module lock"
            fcntl.flock(held_lock, fcntl.LOCK_UN)
        stdout, stderr = waiting.communicate(timeout=10)
        assert waiting.returncode == 0, stdout + stderr
    print("PASS output safety")


def check_fresh_build(compiler, temporary):
    work = temporary / "fresh-business"
    shutil.copytree(FIXTURES / "business", work)
    for output in work.rglob("*_tgo.go"):
        if output.read_bytes().startswith(GENERATED_HEADER):
            output.unlink()

    stale = work / "gobridge" / "stale_tgo.go"
    stale.write_bytes(GENERATED_HEADER + b"\npackage gobridge\n\ntype\n")

    run([str(compiler), "build", "./app"], work)
    required = [
        work / "model" / "model_tgo.go",
        work / "bridge" / "bridge_tgo.go",
        work / "app" / "go_reexport_tgo.go",
    ]
    for output in required:
        assert output.exists(), f"fresh build missed {output.relative_to(work)}"
    assert not stale.exists(), "fresh build kept an orphan bridge output"
    assert (work / "gobridge" / "bridge.go").exists()
    run(["go", "test", "./..."], work)
    print("PASS fresh dependency build")


