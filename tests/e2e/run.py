#!/usr/bin/env python3
"""Build the CLI, compile fixture packages, then run their Go tests."""

from pathlib import Path
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = Path(__file__).parent / "testdata"
ERROR_CASES = FIXTURES / "errors"


def run(command, cwd, *, success=True, env=None):
    result = subprocess.run(
        command,
        cwd=cwd,
        text=True,
        capture_output=True,
        env=env,
    )
    if (result.returncode == 0) != success:
        raise AssertionError(
            f"{command} exited {result.returncode}\n{result.stdout}{result.stderr}"
        )
    return result.stdout + result.stderr


def check_direct_ffi(work):
    generated = (work / "app" / "ffi_tgo.go").read_text()
    calls = [
        "store.Load(id)",
        "legacy.Map(accounts",
        "legacy.Stream(accounts...)",
        "legacy.Update(account",
        "legacy.TypedNilError()",
        "legacy.Wrap(prefix, values...)",
    ]
    for call in calls:
        assert call in generated, f"generated FFI call is not direct: {call}"


def check_stale_output_cleanup(compiler, work):
    source = work / "app" / "obsolete.tgo"
    output = work / "app" / "obsolete_tgo.go"
    source.write_text("package app\n\nfunc Obsolete() int { return 1 }\n")
    run([str(compiler), "build", "./app"], work)
    assert output.exists(), "compiler did not write the temporary output"

    source.unlink()
    invalid = work / "z_invalid"
    invalid.mkdir()
    (invalid / "invalid.tgo").write_text("package invalid\n\nvar missing int\n")
    run([str(compiler), "build", "./..."], work, success=False)
    assert output.exists(), "failed build did not restore stale output"
    shutil.rmtree(invalid)

    run([str(compiler), "build", "./app"], work)
    assert not output.exists(), "compiler kept stale generated output"

    user_file = work / "app" / "manual_tgo.go"
    user_file.write_text("package app\n\nfunc Manual() int { return 1 }\n")
    run([str(compiler), "build", "./app"], work)
    assert user_file.exists(), "compiler removed a user-owned _tgo.go file"


def check_package_discovery(compiler, temporary):
    work = temporary / "discovery"
    work.mkdir()
    (work / "go.mod").write_text("module discovery.test\n\ngo 1.27.0\n")

    app = work / "app"
    app.mkdir()
    (app / "app.tgo").write_text(
        'package app\n\nimport "discovery.test/dep"\n\n'
        "func Answer() int { return dep.Answer() }\n"
    )
    dep = work / "dep"
    dep.mkdir()
    (dep / "dep.tgo").write_text(
        "package dep\n\nfunc Answer() int { return 42 }\n"
    )
    (app / "excluded.tgo").write_text(
        "//go:build tgo_tag_that_is_not_set\n\npackage app\n\ntype\n"
    )
    goos = run(["go", "env", "GOOS"], work).strip()
    goarch = run(["go", "env", "GOARCH"], work).strip()
    other_goos = "windows" if goos != "windows" else "linux"
    target_env = {**os.environ, "GOOS": other_goos, "GOARCH": "amd64"}
    (app / f"platform_{goos}.tgo").write_text(
        "package app\n\nfunc Platform() string { return \"host\" }\n"
    )
    (app / f"platform_{other_goos}.tgo").write_text(
        "package app\n\nfunc Platform() string { return \"other\" }\n"
    )
    (app / f"pair_{goos}_{goarch}.tgo").write_text(
        "package app\n\nfunc Pair() string { return \"host\" }\n"
    )
    (app / f"pair_{other_goos}_amd64.tgo").write_text(
        "package app\n\nfunc Pair() string { return \"other\" }\n"
    )
    (app / "tagged_host.tgo").write_text(
        f"//go:build {goos}\n\npackage app\n\n"
        'func Tagged() string { return "host" }\n'
    )
    (app / "tagged_other.tgo").write_text(
        f"//go:build {other_goos}\n\npackage app\n\n"
        'func Tagged() string { return "other" }\n'
    )
    (app / "legacy_hurd.tgo").write_text("package app\n\ntype\n")
    legacy_output = app / "legacy_tgo_hurd.go"
    legacy_output.write_text(
        "// Code generated by tgo. DO NOT EDIT.\n\npackage app\n\ntype\n"
    )
    (app / "helper_test.tgo").write_text("package app\n\ntype\n")
    (app / "_ignored.tgo").write_text("package app\n\ntype\n")
    (app / ".ignored.tgo").write_text("package app\n\ntype\n")

    broken = work / "broken"
    broken.mkdir()
    (broken / "broken.tgo").write_text("package broken\n\ntype\n")
    (broken / "broken.go").write_text("package broken\n\ntype\n")
    for directory in [work / ".hidden", work / "_private", work / "testdata", work / "vendor"]:
        directory.mkdir()
        (directory / "broken.tgo").write_text("package broken\n\ntype\n")
    nested = work / "nested"
    nested.mkdir()
    (nested / "go.mod").write_text("module nested.test\n\ngo 1.27.0\n")
    (nested / "broken.tgo").write_text("package broken\n\ntype\n")

    run([str(compiler), "build", "./app"], work)
    assert (app / "app_tgo.go").exists(), "selected package did not build"
    assert (dep / "dep_tgo.go").exists(), "local dependency did not build"
    assert not (app / "excluded_tgo.go").exists(), "tagged source built"
    foreign_output = app / f"platform_tgo_{other_goos}.go"
    assert not foreign_output.exists(), "foreign target source built"
    host_output = app / f"platform_tgo_{goos}.go"
    assert host_output.exists(), "host target source did not build"
    host_pair = app / f"pair_tgo_{goos}_{goarch}.go"
    assert host_pair.exists(), "host target pair did not build"
    assert (app / "tagged_host_tgo.go").exists(), "host tag source did not build"
    assert not (app / "tagged_other_tgo.go").exists(), "foreign tag source built"
    assert legacy_output.exists(), "compiler removed a reserved target output"
    run([str(compiler), "build", "./app"], work, env=target_env)
    assert foreign_output.exists(), "foreign target source did not build"
    assert (app / f"pair_tgo_{other_goos}_amd64.go").exists()
    assert host_output.exists(), "foreign build removed host target output"
    assert (app / "tagged_other_tgo.go").exists(), "foreign tag source did not build"
    run(["go", "build", "./app"], work)
    run(["go", "build", "./app"], work, env=target_env)
    run([str(compiler), "build", "./..."], work, success=False)
    shutil.rmtree(broken)
    run([str(compiler), "build", "./..."], work)

    generated = (app / "app_tgo.go").read_bytes()
    manual = app / "manual_tgo.go"
    manual.write_text("package app\n\nvar Broken MissingType\n")
    output = run([str(compiler), "build", "./app"], work, success=False)
    assert "undefined: MissingType" in output, output
    assert (app / "app_tgo.go").read_bytes() == generated
    manual.unlink()

    orphan = work / "orphan"
    orphan.mkdir()
    source = orphan / "only.tgo"
    output = orphan / "only_tgo.go"
    source.write_text("package orphan\n\nfunc Live() bool { return true }\n")
    foreign_source = orphan / f"foreign_{other_goos}.tgo"
    foreign_source.write_text(
        "package orphan\n\nfunc Foreign() bool { return true }\n"
    )
    foreign_orphan_output = orphan / f"foreign_tgo_{other_goos}.go"
    run([str(compiler), "build", "./orphan"], work, env=target_env)
    assert foreign_orphan_output.exists(), "foreign output did not build"
    run([str(compiler), "build", "./orphan"], work)
    assert output.exists(), "orphan fixture did not build"
    source.unlink()
    failure = work / "z_failure"
    failure.mkdir()
    (failure / "failure.tgo").write_text("package failure\n\ntype\n")
    run(
        [str(compiler), "build", "./orphan", "./z_failure"],
        work,
        success=False,
    )
    assert output.exists(), "failed build did not restore deleted output"
    shutil.rmtree(failure)
    run([str(compiler), "build", "./orphan"], work)
    assert not output.exists(), "last deleted source left generated output"
    assert foreign_orphan_output.exists(), "cleanup removed an inactive target output"
    print("PASS package discovery")


def normalize_output(output, work):
    return output.replace(str(work), "<WORK>")


def check_fixture_format():
    files = sorted(str(path) for path in FIXTURES.rglob("*.go"))
    output = run(["gofmt", "-d", *files], ROOT)
    assert output == "", f"format committed fixture Go files\n{output}"
    print("PASS fixture Go formatting")


def check_error_cases(compiler, temporary, update):
    passed = 0
    for source in sorted(ERROR_CASES.glob("*.tgo")):
        work = temporary / "errors" / source.stem
        work.mkdir(parents=True)
        shutil.copyfile(source, work / "input.tgo")
        (work / "go.mod").write_text("module error.test\n\ngo 1.27.0\n")
        result = subprocess.run(
            [str(compiler), "build"],
            cwd=work,
            text=True,
            capture_output=True,
        )
        assert result.returncode == 1, f"{source.name} did not fail"
        actual = {
            ".stdout": normalize_output(result.stdout, work),
            ".stderr": normalize_output(result.stderr, work),
        }
        for suffix, output in actual.items():
            expected = source.with_suffix(suffix)
            if update:
                expected.write_text(output)
            else:
                assert output == expected.read_text(), f"wrong {expected.name}\n{output}"
        assert not list(work.glob("*_tgo.go")), f"{source.name} wrote Go output"
        passed += 1
    print(f"PASS {passed} compiler error reports")


def main():
    update = "--update-errors" in sys.argv[1:]
    check_fixture_format()
    with tempfile.TemporaryDirectory(prefix="tgo-e2e-") as temporary:
        temporary = Path(temporary)
        compiler = temporary / "tgo"
        run(["go", "build", "-o", str(compiler), "./cmd/tgo"], ROOT)
        for fixture in sorted(FIXTURES.iterdir()):
            if not (fixture / "go.mod").exists():
                continue
            work = temporary / fixture.name
            shutil.copytree(fixture, work)
            committed = {path: path.read_bytes() for path in work.rglob("*_tgo.go")}
            run([str(compiler), "build", "./..."], work)
            for path, expected in committed.items():
                assert path.read_bytes() == expected, f"regenerate committed output: {path}"
            if fixture.name == "business":
                check_direct_ffi(work)
            outputs = {path: path.read_bytes() for path in work.rglob("*_tgo.go")}
            run([str(compiler), "build", "./..."], work)
            assert outputs == {path: path.read_bytes() for path in outputs}
            if fixture.name == "business":
                check_stale_output_cleanup(compiler, work)
            run(["go", "test", "./..."], work)
            print(f"PASS {fixture.name}")

        check_package_discovery(compiler, temporary)

        invalid = temporary / "invalid"
        invalid.mkdir()
        (invalid / "go.mod").write_text("module invalid.test\n\ngo 1.27.0\n")
        cases = [
            ("var x int", "variables need an initializer"),
            ("type S struct { N int }; var x = S{}", "missing required field N"),
            ("type Q int where value > 0\nvar x = Q{}", "use a constructor for Q"),
            ("type Q int where value > 0\nvar x = new(Q)", "invalid zero value"),
            ("type Q int where value > 0\nvar x = make([]Q, 2)", "constant length 0"),
            (
                "type Q int where value > 0\nfunc(q Q) Break() Q { return Q{} }",
                "use a constructor for Q",
            ),
            (
                "type Q int where value > 0\nfunc f(xs []Q) { clear(xs) }",
                "clear would create invalid slice elements",
            ),
            (
                "type Q int where value > 0\n"
                "func f(xs []Q, n int) []Q { return xs[:n] }",
                "reslice bound must be proven",
            ),
            (
                "type Q int where value > 0\n"
                "func f(xs []Q, n int) []Q { "
                "if n <= len(xs) { n++; return xs[:n] }; return xs }",
                "reslice bound must be proven",
            ),
            (
                "type Q int where value > 0\n"
                "func f(xs map[int]Q) Q { return xs[0] }",
                "this read needs if value, ok",
            ),
            (
                "type Q int where value > 0\n"
                "func f(xs map[int]Q) int { "
                "if value, ok := xs[0]; ok { return value.Value() } "
                "else { return value.Value() } }",
                "value is available only in the successful presence branch",
            ),
            (
                "type Q int where value > 0\n"
                "func f(xs <-chan Q) Q { return <-xs }",
                "this read needs if value, ok",
            ),
            (
                "type Q int where value > 0\n"
                "func f(value any) Q { return value.(Q) }",
                "this read needs if value, ok",
            ),
            ("var x = [2]int{1}", "supply every index"),
            ("var x = []int{2: 1}", "supply every index"),
            (
                "type A enum { One struct {}; Two struct {} }\n"
                "func f(a A) { match a { case One(_): return } }",
                "missing variant Two",
            ),
        ]
        for source, message in cases:
            (invalid / "bad.tgo").write_text("package invalid\n" + source + "\n")
            output = run([str(compiler), "build"], invalid, success=False)
            assert message in output, (message, output)
            assert not list(invalid.glob("*_tgo.go")), "failed build wrote output"
        print(f"PASS {len(cases)} rejected source cases")
        check_error_cases(compiler, temporary, update)


if __name__ == "__main__":
    main()
