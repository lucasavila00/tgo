// Package tgolint checks Go callers of generated tgo types.
package tgolint

import (
	"go/ast"
	"go/token"
	"go/types"

	"golang.org/x/tools/go/analysis"
)

const generatedHeader = "// Code generated by tgo. DO NOT EDIT."

// Analyzer checks unsafe Go use of generated tgo values.
var Analyzer = &analysis.Analyzer{
	Name:      "tgolint",
	Doc:       "check Go use of generated tgo types",
	Run:       run,
	FactTypes: []analysis.Fact{new(modelFact)},
}

type checker struct {
	pass      *analysis.Pass
	models    map[objectKey]*modelFact
	generated map[*ast.File]bool
	parents   map[ast.Node]ast.Node
	safe      map[*ast.SelectorExpr]bool
	handled   map[*ast.SelectorExpr]bool
	checked   map[*ast.CallExpr]bool
	presence  map[ast.Expr]bool
	escaped   map[types.Object]token.Pos
	reported  map[diagnosticKey]bool
}

type diagnosticKey struct {
	position token.Pos
	message  string
}

func run(pass *analysis.Pass) (any, error) {
	c := &checker{
		pass:      pass,
		models:    make(map[objectKey]*modelFact),
		generated: make(map[*ast.File]bool),
		parents:   make(map[ast.Node]ast.Node),
		safe:      make(map[*ast.SelectorExpr]bool),
		handled:   make(map[*ast.SelectorExpr]bool),
		checked:   make(map[*ast.CallExpr]bool),
		presence:  make(map[ast.Expr]bool),
		reported:  make(map[diagnosticKey]bool),
	}
	c.findModels()
	for _, file := range pass.Files {
		if c.generated[file] {
			continue
		}
		c.addParents(file)
		ast.Inspect(file, func(node ast.Node) bool {
			if statement, ok := node.(*ast.SwitchStmt); ok {
				c.checkTagSwitch(statement)
			}
			return true
		})
		ast.Inspect(file, func(node ast.Node) bool {
			c.checkNode(node)
			return true
		})
	}
	return nil, nil
}

func (c *checker) addParents(file *ast.File) {
	var stack []ast.Node
	ast.Inspect(file, func(node ast.Node) bool {
		if node == nil {
			stack = stack[:len(stack)-1]
			return false
		}
		if len(stack) > 0 {
			c.parents[node] = stack[len(stack)-1]
		}
		stack = append(stack, node)
		return true
	})
}

func (c *checker) checkNode(node ast.Node) {
	switch node := node.(type) {
	case *ast.FuncDecl:
		if node.Body != nil {
			c.checkNamedResults(node.Type)
			c.checkConstructors(node.Body)
		}
	case *ast.FuncLit:
		c.checkNamedResults(node.Type)
		c.checkConstructors(node.Body)
	case *ast.TypeSpec:
		c.checkTypeSpec(node)
	case *ast.ValueSpec:
		c.checkValueSpec(node)
	case *ast.CompositeLit:
		c.checkLiteral(node)
	case *ast.CallExpr:
		c.checkCall(node)
	case *ast.IndexExpr:
		c.checkMapRead(node)
	case *ast.UnaryExpr:
		if node.Op == token.ARROW {
			c.checkPresenceRead(node)
		}
	case *ast.TypeAssertExpr:
		if node.Type != nil {
			c.checkPresenceRead(node)
		}
	case *ast.SelectorExpr:
		c.checkRepresentationAccess(node)
	case *ast.SliceExpr:
		c.checkReslice(node)
	}
}
